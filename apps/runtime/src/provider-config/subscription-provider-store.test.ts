import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { ProviderConfigStore } from './provider-config-store'
const output = resolve(import.meta.dirname, '../../../../output/model-router-stage3')
async function fixture() { await mkdir(output, { recursive: true }); const root = await mkdtemp(join(output, 'store-')); return { root, store: new ProviderConfigStore(root) } }
const input = (name: string, ref: string, provider: 'codex' | 'antigravity' = 'codex') => ({ name, modelMapping: { opus: 'gpt-5.4', sonnet: 'gpt-5.4', haiku: 'gpt-5.4' }, subscription: { provider, credentialRef: { name: ref, authIndex: 'private-index' }, account: { email: 'test@example.invalid', plan: 'Plus', status: 'ready' as const }, modelMetadata: [{ id: 'gpt-5.4', contextWindow: 400000 }] } })
describe('version 1 subscription provider persistence', () => {
  it('keeps legacy API key rows and global selection, adds one subscription of each kind, and masks credential references', async () => {
    const { store, root } = await fixture()
    const api = await store.upsert({ cli: 'claude-code', name: 'Existing API', model: 'api-model', endpoint: 'https://example.invalid', apiKey: 'secret-key' })
    await store.activate('claude-code', api.id)
    const first = await store.adoptSubscription(input('ChatGPT', 'first.json'))
    const second = await store.adoptSubscription(input('Replacement', 'second.json'))
    expect(second.id).toBe(first.id)
    await expect(store.adoptSubscription(input('Google', 'google.json', 'antigravity'))).rejects.toThrow('risk confirmation')
    await store.confirmAntigravityRisk()
    await store.adoptSubscription(input('Google', 'google.json', 'antigravity'))
    const reopened = new ProviderConfigStore(root), snapshot = await reopened.snapshot()
    expect(snapshot.activeProviderIds['claude-code']).toBe(api.id)
    expect(snapshot.providers['claude-code']).toHaveLength(4)
    expect(await reopened.antigravityRiskAccepted()).toBe(true)
    const raw = JSON.parse(await readFile(join(root, 'provider-config.json'), 'utf8'))
    expect(raw.version).toBe(1)
    expect(raw.providers['claude-code'].filter((row: { kind?: string }) => row.kind === 'subscription')).toHaveLength(2)
    const publicJson = JSON.stringify(snapshot)
    for (const secret of ['credentialRef', 'private-index', 'secret-key', 'second.json', 'access_token', 'refresh_token']) expect(publicJson).not.toContain(secret)
    expect((await reopened.subscriptions())[0]?.subscription.credentialRef.name).toBe('second.json')
    expect((await reopened.launchSelection('claude-code', api.id)).env.ANTHROPIC_API_KEY).toBe('secret-key')
  })
  it('reads an unchanged version 1 file without kind or policies', async () => {
    const { store, root } = await fixture(), original = await store.snapshot()
    const legacy = { version: 1, ...original, futureOption: { keep: true }, policies: { futurePolicy: 7 } }
    Object.assign(legacy.providers['claude-code'][0]!, { futureProviderOption: 'retained' })
    await writeFile(join(root, 'provider-config.json'), JSON.stringify(legacy))
    const reopenedSnapshot = await new ProviderConfigStore(root).snapshot()
    expect(reopenedSnapshot.activeProviderIds).toEqual(original.activeProviderIds)
    expect(reopenedSnapshot.providers['claude-code'][0]?.kind).toBeUndefined()
    expect(await store.antigravityRiskAccepted()).toBe(false)
    await store.confirmAntigravityRisk()
    const written = JSON.parse(await readFile(join(root, 'provider-config.json'), 'utf8'))
    expect(written.futureOption).toEqual({ keep: true })
    expect(written.policies.futurePolicy).toBe(7)
    expect(written.providers['claude-code'][0].futureProviderOption).toBe('retained')
  })
  it('rejects forged references and unavailable models while projecting an internal Opus launch selection', async () => {
    const { store } = await fixture(), value = input('ChatGPT', 'valid.json')
    const saved = await store.adoptSubscription(value)
    await expect(store.adoptSubscription({ ...value, id: 'foreign' })).rejects.toThrow('identity')
    await expect(store.adoptSubscription(input('Bad', '../escape.json'))).rejects.toThrow('reference')
    await expect(store.adoptSubscription({ ...value, modelMapping: { ...value.modelMapping, opus: 'not-available' } })).rejects.toThrow('not available')
    await expect(store.upsert({ kind: 'subscription', cli: 'claude-code', name: 'Forged', modelMapping: value.modelMapping, subscription: { provider: 'codex' } })).rejects.toThrow('completed sign-in')
    expect((await store.activate('claude-code', saved.id)).activeProviderIds['claude-code']).toBe(saved.id)
    const selection = await store.launchSelection('claude-code', saved.id)
    expect(selection.model).toBe('matou-chatgpt/matou-opus')
    expect(selection.env).toEqual({})
    expect(selection.subscription?.subscription.credentialRef.name).toBe('valid.json')
  })
})
