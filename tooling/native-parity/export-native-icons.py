"""Reuse the frozen AppIcon paths in the native application's embedded assets."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
source = root / "apps/desktop/src/renderer/src/ui/AppIcon.tsx"
destination = root / "apps/native/desktop/assets/icons"
destination.mkdir(parents=True, exist_ok=True)
names = []
for line in source.read_text().split("const paths:", 1)[1].splitlines():
    match = re.match(r"\s*(?:'([^']+)'|([\w-]+)):\s*(<.*>),?$", line)
    if not match:
        continue
    name = match[1] or match[2]
    body = match[3].removeprefix("<>").removesuffix("</>")
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" '
           'fill="none" stroke="currentColor" stroke-width="1.75" '
           'stroke-linecap="round" stroke-linejoin="round">' + body + '</svg>\n')
    (destination / f"{name}.svg").write_text(svg)
    names.append(name)
declared = re.findall(r"\| '([^']+)'", source.read_text().split("export function", 1)[0])
assert set(names) == set(declared), (names, declared)
task = root / "apps/desktop/src/renderer/src/assets/terminal-reference/terminal/dark_lujing.svg"
(destination / "task.svg").write_bytes(task.read_bytes())
names.append("task")
updates = (root / "apps/desktop/src/renderer/src/updates/AppUpdateControl.tsx").read_text()
download = re.search(r'function DownloadIcon\(\)\s*\{\s*return (<svg.*?</svg>)', updates, re.S)
assert download
download_svg = download[1].replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ', 1)
for jsx, xml in [('strokeWidth', 'stroke-width'), ('strokeLinecap', 'stroke-linecap'), ('strokeLinejoin', 'stroke-linejoin')]:
    download_svg = download_svg.replace(jsx, xml)
(destination / "download.svg").write_text(download_svg + '\n')
names.append("download")
arms = "\n".join(f'            "icons/{name}.svg" => include_bytes!("../assets/icons/{name}.svg"),' for name in names)
output = '''// Generated by tooling/native-parity/export-native-icons.py from frozen UI assets.
use std::borrow::Cow;
use gpui::{AssetSource, SharedString};

pub struct NativeAssets;
impl AssetSource for NativeAssets {
    fn load(&self, path: &str) -> anyhow::Result<Option<Cow<'static, [u8]>>> {
        let bytes: &'static [u8] = match path {
ARMS
            _ => return Ok(None),
        };
        Ok(Some(Cow::Borrowed(bytes)))
    }
    fn list(&self, _: &str) -> anyhow::Result<Vec<SharedString>> { Ok(Vec::new()) }
}
'''.replace("ARMS", arms)
(root / "apps/native/desktop/src/assets.rs").write_text(output)
print(f"Exported {len(names)} original icons")
