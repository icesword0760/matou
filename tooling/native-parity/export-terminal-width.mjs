// Export the frozen renderer's default Unicode 6 width policy for Ghostty's
// generated lookup table. No substitution of the terminal's original bytes.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

const require = createRequire(resolve('apps/runtime/package.json'));
const { Terminal } = require('@xterm/headless');
const terminal = new Terminal({ allowProposedApi: true });
if (terminal.unicode.activeVersion !== '6') throw new Error('Frozen Unicode version changed');
const widths = terminal._core.unicodeService;
const runs = [];
for (let cp = 0, start = 0, width = widths.wcwidth(0); cp <= 0x110000; cp++) {
  const next = cp === 0x110000 ? -1 : widths.wcwidth(cp);
  if (next !== width) {
    if (width !== 1) runs.push([start, cp - 1, width]);
    start = cp; width = next;
  }
}
terminal.dispose();
const directory = resolve('apps/native/terminal/native');
mkdirSync(directory, { recursive: true });
const code = `// Generated by tooling/native-parity/export-terminal-width.mjs.
// xterm.js 6.0.0 default Unicode 6 policy; see xterm-LICENSE.
const Range = struct { first: u21, last: u21, width: u2 };
const ranges = [_]Range{
${runs.map(([a, b, w]) => `    .{ .first = 0x${a.toString(16)}, .last = 0x${b.toString(16)}, .width = ${w} },`).join('\n')}
};

pub fn get(cp: u21) u2 {
    var left: usize = 0;
    var right: usize = ranges.len;
    while (left < right) {
        const middle = left + (right - left) / 2;
        const range = ranges[middle];
        if (cp < range.first) { right = middle; }
        else if (cp > range.last) { left = middle + 1; }
        else { return range.width; }
    }
    return 1;
}
`;
writeFileSync(resolve(directory, 'reference_width.zig'), code);
const rendererRequire = createRequire(resolve('apps/desktop/package.json'));
const packageRoot = resolve(rendererRequire.resolve('@xterm/xterm'), '../..');
writeFileSync(resolve(directory, 'xterm-LICENSE'), readFileSync(resolve(packageRoot, 'LICENSE')));
console.log(`Exported ${runs.length} non-default width ranges from Unicode 6`);
