#!/usr/bin/env python3
"""Simulate a provider resuming from compaction and redrawing its screen."""
import json
import os
from pathlib import Path
import sys
import time
from urllib.parse import urlparse
from urllib.request import build_opener, ProxyHandler, Request

args = sys.argv[1:]
if "--resume" not in args:
    sys.exit(0)

session_id = args[args.index("--resume") + 1]
settings_arg = args[args.index("--settings") + 1]
settings = json.loads(settings_arg if settings_arg.startswith("{") else Path(settings_arg).read_text())
hook = settings["hooks"]["SessionStart"][0]["hooks"][0]["url"]
assert urlparse(hook).hostname == "127.0.0.1"

launches = Path(os.environ["MATOU_HISTORY_LAUNCHES"])
first_launch = not launches.exists()
with launches.open("a") as log:
    log.write(json.dumps({
        "pid": os.getpid(), "ppid": os.getppid(), "sessionId": session_id,
        "timestamp": time.time_ns() // 1_000_000,
        "argv": args[:args.index("--settings") + 1] + ["<fixture settings>"] + args[args.index("--settings") + 2:],
    }) + "\n")

permission_mode = "bypassPermissions" if "--dangerously-skip-permissions" in args else "default"
opener = build_opener(ProxyHandler({}))
for event in ("SessionStart", "Stop"):
    body = {
        "hook_event_name": event,
        "session_id": session_id,
        "cwd": os.getcwd(),
        "transcript_path": os.environ["MATOU_HISTORY_TRANSCRIPT"],
        "permission_mode": permission_mode,
    }
    request = Request(hook, data=json.dumps(body).encode(), headers={"Content-Type": "application/json"})
    with opener.open(request, timeout=3) as response:
        response.read()

# Exercise a full provider redraw with only the post-compaction conversation.
# The original scrollback marker is generated by the first process only.
print("\x1b[2J\x1b[HPOST_COMPACTION_SCREEN", flush=True)
if first_launch:
    print("FIRST_RUN_SCROLLBACK_MARKER", flush=True)
else:
    print(f"RESUMED_PROCESS:{os.getpid()}", flush=True)

for line in sys.stdin:
    print("INPUT_OK:" + line.strip(), flush=True)
